def bracket_of(depth):
    """按深度取分档序号（0-based），返回 None 表示超出表范围"""
    for i, (a, b) in enumerate(DEPTH_BRACKETS):
        if a < depth <= b:
            return i
    return None


def price_at(table_id, depth, col_index):
    """按深度自动分档取基价（含超出末档的递增规则）"""
    import math
    t = TABLES[table_id]
    for r in t["rows"]:
        rng = r.get("rng")
        if not rng:
            continue
        if rng[0] < depth <= rng[1]:
            return r["vals"][col_index] if col_index < len(r["vals"]) else None
    tail = t.get("tail")
    if tail:
        last = t["rows"][-1]["vals"][col_index]
        if last is None:
            return None
        n2 = math.ceil((depth - tail["start"]) / tail["step"])
        return last * (tail["factor"] ** n2)
    return None


