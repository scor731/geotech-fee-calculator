# 测量项目「族」：界面上按收费标准的表格样式逐行列出，
# 行的第二列（黄色）由用户按等级 / 比例尺选择，对应到 SURVEY_ITEMS 中的具体基价行。
#   opts 为空表示该项无档次可选（只有一个基价）
# ---------------------------------------------------------------------------
def _fam(id, grp, name, unit, opts=None, vlabel="档次"):
    """opts 每项为 (显示名, 基价行 id) 或 (显示名, 基价行 id, 计费单位)；
    第三项用于同一项目族内单位随档次变化的场合（如导线→图根点，单位由 km 变为点）。"""
    out = []
    for o in (opts or []):
        d = {"label": o[0], "id": o[1]}
        if len(o) > 2:
            d["unit"] = o[2]
        out.append(d)
    return {"id": id, "grp": grp, "name": name, "unit": unit, "vlabel": vlabel,
            "opts": out}


def _scales(pre, suffix="", upto=10000, start=200):
    lab = [("1:200", "200"), ("1:500", "500"), ("1:1000", "1000"),
           ("1:2000", "2000"), ("1:5000", "5000"), ("1:10000", "10000")]
    return [(a, pre + b + suffix) for a, b in lab if start <= int(b) <= upto]


